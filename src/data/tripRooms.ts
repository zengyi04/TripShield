import type { WeatherSnapshot } from '../utils/weather';

export type ActivityType = 'flight' | 'hotel' | 'food' | 'attraction' | 'transport';

export interface TransitLeg {
  mode: 'walk' | 'metro' | 'bus' | 'taxi' | 'flight' | 'ferry' | 'rail';
  instruction: string;
  line?: string;
  durationMin: number;
}

export interface TripActivity {
  time: string;
  place: string;
  type: ActivityType;
  note?: string;
  address: string;
  lat: number;
  lng: number;
  mapsQuery: string;
  /** Optional real photo shown in route modal before map tiles. */
  previewImageUrl?: string;
  weather: WeatherSnapshot;
  route: {
    from: string;
    summary: string;
    durationMin: number;
    fare: string;
    mapsUrl: string;
    legs: TransitLeg[];
  };
}

export interface TripDay {
  isoDate: string;
  date: string;
  weekday: string;
  label: string;
  activities: TripActivity[];
}

export interface RoomCondition {
  id: string;
  icon: string;
  label: string;
  detail: string;
  impactScore: number;
  active: boolean;
}

export interface RoomPlan {
  id: string;
  name: string;
  destination: string;
  city: string;
  timezone: string;
  dateRange: string;
  members: number;
  memberNames: string[];
  emoji: string;
  accentColor: string;
  baseScore: number;
  days: TripDay[];
  optimizedDays: TripDay[];
  conditions: RoomCondition[];
}

const wx = (
  icon: WeatherSnapshot['icon'],
  emoji: string,
  condition: string,
  tempC: number,
  extra?: Partial<WeatherSnapshot>,
): WeatherSnapshot => ({
  icon,
  emoji,
  condition,
  tempC,
  feelsLikeC: extra?.feelsLikeC ?? tempC + 1,
  humidity: extra?.humidity ?? 68,
  windKph: extra?.windKph ?? 12,
  precipChance: extra?.precipChance ?? 20,
  source: extra?.source ?? 'OpenWeather forecast cache',
  live: false,
});

const mapsDir = (from: string, to: string) =>
  `https://www.google.com/maps/dir/?api=1&origin=${encodeURIComponent(from)}&destination=${encodeURIComponent(to)}&travelmode=transit`;

const stop = (
  time: string,
  place: string,
  type: ActivityType,
  note: string,
  address: string,
  lat: number,
  lng: number,
  mapsQuery: string,
  weather: WeatherSnapshot,
  from: string,
  summary: string,
  durationMin: number,
  fare: string,
  legs: TransitLeg[],
): TripActivity => ({
  time,
  place,
  type,
  note,
  address,
  lat,
  lng,
  mapsQuery,
  weather,
  route: { from, summary, durationMin, fare, mapsUrl: mapsDir(from, mapsQuery), legs },
});

